'use strict';
// Invented-only before/after proof for resolving a date once inside one hold
// computation. The reference removes only that optimization, restoring the
// incumbent per-transaction algorithm. No production test seam or cache flag.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const World = require('./fixtures/held-other-income-search-world');
const FILE = path.resolve(__dirname, '../public/forecast.js');
const source = fs.readFileSync(FILE, 'utf8');
const BEGIN = '  function computeHeldOtherIncomeKeys(';
const END = '\n  // Machine-readable settlement fact';
const begin = source.indexOf(BEGIN), end = source.indexOf(END, begin);
assert.ok(begin >= 0 && end > begin, 'one bounded computation is instrumented');
const body = source.slice(begin, end);
const DATE_SET = '    const seenDates = new Set();\n';
const DATE_SKIP = '      if (seenDates.has(tx.date)) continue;\n      seenDates.add(tx.date);\n';
const CYCLE = '      const cycle = spendingCycle(plan, tx.date);';
for (const anchor of [DATE_SET, DATE_SKIP, CYCLE]) {
  assert.equal(body.split(anchor).length, 2, 'exactly one proof anchor');
}
function compile(mode) {
  let region = body;
  if (mode === 'reference') region = region.replace(DATE_SET, '').replace(DATE_SKIP, '');
  if (mode === 'forget-windows') region = region.replace(
    "windows.push({ id: 'held-' + cycle.start, start: cycle.start, end: cycle.end });", '/* mutant drops every resolved window */');
  region = region.replace(CYCLE, '      __dateProofCalls++;\n' + CYCLE);
  let code = 'let __dateProofCalls = 0;\n' + source.slice(0, begin) + region + source.slice(end);
  code = code.replace('  const Forecast = {', '  const Forecast = {\n'
    + '    __heldKeys: computeHeldOtherIncomeKeys,\n'
    + '    __resetDateCalls: () => { __dateProofCalls = 0; },\n'
    + '    __dateCalls: () => __dateProofCalls,');
  const mod = new Module(FILE, module);
  mod.filename = FILE;
  mod.paths = Module._nodeModulePaths(path.dirname(FILE));
  mod._compile(code, FILE);
  return mod.exports;
}
const reference = compile('reference'), candidate = compile('candidate'), mutant = compile('forget-windows');
const AS_OF = '2026-11-10';
const HELD = { rebate: { date: '2026-11-12', amount: 200 },
  receipts: [{ id: 'gift', date: '2026-11-08', amount: 50 }] };
function keys(F, data, events = []) {
  F.__resetDateCalls();
  const opts = World.recommendOptions(data);
  const result = F.__heldKeys(data.plan, opts, AS_OF, events, opts.currentPeriodActuals.transactions);
  return { result: { keys: [...result.keys].sort(), fromEvents: result.fromEvents }, calls: F.__dateCalls() };
}
function equalKeys(label, data, events = []) {
  const before = keys(reference, data, events), after = keys(candidate, data, events);
  assert.deepStrictEqual(after.result, before.result, label + ': hold keys and fallback unchanged');
  assert.ok(after.calls <= before.calls, label + ': no additional cycle resolutions');
  console.log('PASS ' + label);
  return { before, after };
}

// Explicit boundary dates, reverse order, duplicates, malformed dates and a
// linked-only date. The listed boundaries are hand-counted from the invented
// fortnightly 2026-10-02 anchor, not generated by spendingCycle.
const boundary = World.build({ ...HELD, transactions: 0, days: 60 });
const packet = boundary.liveOverlay.currentPeriodActuals;
const receipt = packet.transactions.find(tx => tx.categoryLabel === 'Other Income');
assert.ok(receipt, 'invented receipt survives normalization');
const dates = ['2026-11-13', '2026-11-12', '2026-10-30', '2026-10-29'];
packet.transactions = [{ ...receipt, id: 'linked-before-receipt' }].concat(dates.flatMap((date, i) => [0, 1, 2].map(n => ({
  ...receipt, id: 'boundary-' + i + '-' + n, date, amount: 7, isIncome: false, categoryLabel: 'Groceries',
})))).concat([receipt, { ...receipt, id: 'linked-only', date: '2026-10-01' },
  null, { ...receipt, id: 'invalid', date: '2026-02-31' }]);
packet.representedActuals = [{ transactionId: 'linked-only' }, { transactionId: 'linked-before-receipt' }];
let comparison = equalKeys('unsorted duplicate dates across pay-period boundaries', boundary);
assert.equal(comparison.after.calls, 5, 'exactly five valid unlinked dates resolved');
assert.equal(comparison.before.calls, 13, 'incumbent resolves all thirteen eligible rows');
assert.ok(comparison.after.result.keys.includes('rebate@2026-11-12'), 'receipt actually holds the expected rebate');
assert.notDeepStrictEqual(keys(mutant, boundary).result, comparison.before.result,
  'teeth: dropping resolved windows changes the held answer');

// Reuse the same plan and packet identities: no state may survive a call.
boundary.plan.income.find(row => row.id === 'payroll').anchor = '2026-10-01';
const changedAnchor = equalKeys('edited payroll anchor on the same plan object', boundary);
assert.ok(!changedAnchor.after.result.keys.includes('rebate@2026-11-12'), 'edited anchor changes the hold period');
boundary.plan.income.find(row => row.id === 'payroll').anchor = '2026-10-02';
packet.transactions = packet.transactions.filter(tx => tx && tx.id !== receipt.id);
comparison = equalKeys('edited receipt evidence on the same packet object', boundary);
assert.ok(!comparison.after.result.keys.includes('rebate@2026-11-12'), 'removed receipt releases the hold');

const noPayroll = World.build({ ...HELD, transactions: 40, days: 30 });
noPayroll.plan.income = noPayroll.plan.income.filter(row => row.frequency !== 'biweekly');
comparison = equalKeys('missing payroll retains event-bounded fallback', noPayroll,
  [{ date: '2026-11-20' }, { date: '2026-02-31' }]);
assert.equal(comparison.after.result.fromEvents, true, 'fallback was exercised');
assert.ok(comparison.after.calls < comparison.before.calls, 'unresolved dates also deduplicate');
noPayroll.liveOverlay.currentPeriodActuals.transactions = [];
comparison = equalKeys('empty evidence remains an empty hold', noPayroll);
assert.deepStrictEqual(comparison.after.result, { keys: [], fromEvents: false });

// Complete recommendation equality covers the Budget consumer, including
// money, trust, explanations and period publications; no fields are excluded.
const worlds = [
  ['held, repeated purchase dates', { ...HELD, transactions: 120, days: 30 }],
  ['held with payroll walk', { ...HELD, walk: true, transactions: 268, days: 44 }],
  ['exact receipt settles expectation', { transactions: 80, days: 30,
    rebate: { date: '2026-11-07', amount: 200 }, receipts: [{ id: 'exact', date: '2026-11-07', amount: 200 }] }],
  ['no unlinked receipt', { transactions: 80, days: 30, rebate: HELD.rebate }],
];
for (const [label, options] of worlds) {
  const data = World.build(options), untouched = structuredClone(data);
  reference.__resetDateCalls();
  const before = reference.recommend(data.plan, AS_OF, World.recommendOptions(data));
  const beforeCalls = reference.__dateCalls();
  candidate.__resetDateCalls();
  const after = candidate.recommend(data.plan, AS_OF, World.recommendOptions(data));
  const afterCalls = candidate.__dateCalls();
  assert.deepStrictEqual(after, before, label + ': complete recommendation unchanged');
  assert.deepStrictEqual(data, untouched, label + ': inputs unchanged');
  assert.ok(afterCalls < beforeCalls, label + ': actual recommendation resolves fewer dates');
  console.log('PASS complete recommendation: ' + label + ' (' + beforeCalls + ' -> ' + afterCalls + ' date resolutions)');
}
console.log('ALL CHECKS PASSED');
